import esbuild from "esbuild";
import process from "process";
import { readFileSync } from "node:fs";
import builtins from "builtin-modules";

const interactLicense = readFileSync(new URL("./licenses/interactjs-MIT.txt", import.meta.url), "utf8");
const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
/* Interact.js (MIT)
${interactLicense}
*/
`;

const prod = (process.argv[2] === "production");

const workerPlugin = {
    name: 'pdf-text-worker',
    setup(build) {
        build.onResolve({ filter: /^virtual:pdf-text-worker$/ }, () => ({ path: 'worker', namespace: 'pdf-text-worker' }));
        build.onLoad({ filter: /.*/, namespace: 'pdf-text-worker' }, async () => {
            const worker = await esbuild.build({ entryPoints: ['src/free-text/worker-entry.ts'], bundle: true, write: false,
                platform: 'browser', format: 'iife', target: 'es2020', minify: prod });
            return { contents: `export const source = ${JSON.stringify(worker.outputFiles[0].text)};`, loader: 'js',
                watchFiles: ['src/free-text/worker-entry.ts', 'src/free-text/worker-engine.ts', 'src/free-text/pdf.ts', 'src/free-text/render.ts'] };
        });
    }
};
const context = await esbuild.context({
    plugins: [workerPlugin],
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		"pdfjs-dist",
		...builtins],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}