import {build} from 'esbuild';
import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
globalThis.crypto ??= webcrypto;
const combined=await build({stdin:{contents:"export * from './src/free-text/pdf'; export {PDFDocument,PDFName,PDFDict,PDFArray} from '@cantoo/pdf-lib';",resolveDir:process.cwd()},bundle:true,write:false,format:'esm',platform:'node'});
const api=await import('data:text/javascript;base64,'+Buffer.from(combined.outputFiles[0].text).toString('base64'));
const {validateTextBox,wrapText}=api;
const doc=await api.PDFDocument.create();doc.addPage([595,842]);
const png=Uint8Array.from(Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=','base64'));
const box={page:1,rect:[72,700,330,750],text:'中文批注 / 日本語のメモ / English',fontSize:12,color:'#222222'};
validateTextBox(box);
for(const change of [{text:''},{fontSize:0},{fontSize:NaN},{color:'red'},{rect:[0,0,0,0]},{page:0}])assert.throws(()=>validateTextBox({...box,...change}));
assert.deepEqual(wrapText('中文测试\nnext',20,s=>Array.from(s).length*10),['中文','测试','ne','xt']);
const id=await api.writeTextBox(doc,box,png,'测试作者');
let reloaded=await api.PDFDocument.load(await doc.save());
assert.equal(api.readTextBox(reloaded,1,id).text,box.text,'Unicode Contents survives serialization');
const annotation=reloaded.context.lookup(reloaded.getPage(0).node.Annots().asArray()[0],api.PDFDict);
assert.equal(annotation.get(api.PDFName.of('Subtype')).toString(),'/FreeText');
assert(annotation.lookup(api.PDFName.of('AP'),api.PDFDict).get(api.PDFName.of('N')),'Appearance exists');
const again=await api.writeTextBox(reloaded,{...box,id,text:'修改后的文字',color:'#ff0000'},png,'作者');
assert.equal(again,id,'Editing keeps stable annotation ID');
reloaded=await api.PDFDocument.load(await reloaded.save());
assert.equal(reloaded.getPage(0).node.Annots().size(),1,'Editing does not stack duplicate annotations');
assert.equal(api.readTextBox(reloaded,1,id).text,'修改后的文字');
assert.equal(api.readTextBox(reloaded,1,id).color,'#ff0000');
const id2=await api.writeTextBox(reloaded,{...box,rect:[72,500,330,550]},png,'作者');
api.deleteTextBox(reloaded,1,id);
reloaded=await api.PDFDocument.load(await reloaded.save());
assert.equal(reloaded.getPage(0).node.Annots().size(),1);
assert.equal(api.readTextBox(reloaded,1,id2).text,box.text,'Deleting leaves other notes untouched');
assert.throws(()=>api.readTextBox(reloaded,1,id));
await assert.rejects(()=>api.writeTextBox(reloaded,{...box,rect:[0,-20,200,20]},png,'a'),/超出页面/);
await assert.rejects(()=>api.writeTextBox(reloaded,{...box,id:'999999R'},png,'a'),/修改或删除/);
console.log('Passed: Unicode FreeText, appearance, stable edit IDs, edit/reopen/delete, unaffected notes, text wrapping, bounds and input validation.');
